// Languages of the collector's answers. A player chooses one with the
// plugin's gamewe_lang (logged as `setup "gamewe_lang" (value "de")`);
// otherwise the game's cl_language decides, and English is the default.
var Languages = []string{"en", "de", "ru", "es", "fr", "pt", "nl", "da", "pl"}

// langCode returns the language of a gamewe_lang value or a cl_language
// name ("" if unknown). dk is the gameME name of Danish.
func langCode(v string) string {
	switch v = strings.ToLower(strings.TrimSpace(v)); v {
	case "en", "english":
		return "en"
	case "de", "german":
		return "de"
	case "ru", "russian":
		return "ru"
	case "es", "spanish", "latam":
		return "es"
	case "fr", "french":
		return "fr"
	case "pt", "portuguese", "brazilian":
		return "pt"
	case "nl", "dutch":
		return "nl"
	case "da", "dk", "danish":
		return "da"
	case "pl", "polish":
		return "pl"
	}
	return ""
}

// tr formats the message key in lang, falling back to English for an
// unknown language or a missing key. Every value of catalog[lang] has the
// same verbs as the English one (TestCatalogComplete).
func tr(lang, key string, args ...any) string {
	f, ok := catalog[lang][key]
	if !ok {
		f = catalog["en"][key]
	}
	if len(args) == 0 {
		return f
	}
	return fmt.Sprintf(f, args...)
}

