-- gameWE - collector: HLstatsX database schema (MariaDB / MySQL), utf8mb4.
--
-- The HLstatsX table structure, converted to utf8mb4, with gameWE's
-- additions (hlstats_Servers.rcon_password, hlstats_Games.realgame,
-- server_id on the event tables, hlstats_Events_Latency,
-- hlstats_gamewe_jobs and the indexes the web needs). One unique key uses
-- MariaDB's USING HASH (hlstats_Definition_Ranks_Ribbons), so it needs
-- MariaDB 10.5+.
--
-- Compiled into the collector (internal/schema): `gamewe db migrate`
-- creates a new database from it and seed.sql, and adds to an older gameWE
-- or HLstatsX database the tables, columns and indexes it lacks
-- (docs/DATABASE.md). After editing, run `make schema` (PostgreSQL files)
-- and add a migration in internal/database/migrations.go.

