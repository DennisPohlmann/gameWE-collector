// The SQL Server files are derived from the PostgreSQL ones (themselves
// generated from the MariaDB files), line by line: both use unquoted names,
// identity columns and separate CREATE INDEX statements.

const mssqlSchemaHeader = `-- gameWE - collector: HLstatsX database schema for Microsoft SQL Server (2022 or newer).
` + "-- GENERATED by tools/schemagen from the PostgreSQL file: do not edit, run: make schema\n" + `--
-- The same tables, columns and defaults as internal/schema/postgres/schema.sql
-- (see there for the differences to MariaDB), with these changes:
--   * varchar(n) is nvarchar(n) (Unicode), timestamp is datetime2(0),
--     double precision is float, integer is int; above 4000 characters
--     nvarchar(max)
--   * identity columns are IDENTITY(1,1)
--   * hlstats_Livestats is a normal table
--   * a unique index over a column that may be NULL only covers the rows
--     where it is not NULL (SQL Server allows one NULL in a unique index,
--     MariaDB and PostgreSQL any number)
--
-- Compiled into the collector: gamewe db migrate creates a new database
-- from it (and seed.sql, grants.sql). The database's collation must be
-- case-insensitive (schema/mssql/init/ creates it so).

`

var (
	reMsCreate = regexp.MustCompile(`^CREATE (?:UNLOGGED )?TABLE (\w+) \($`)
	reMsCol    = regexp.MustCompile(`^  (\w+) (.*?)(,?)$`)
	reMsIndex  = regexp.MustCompile(`^CREATE (UNIQUE )?INDEX (\w+) ON (\w+) \((.*)\);$`)
	reMsPK     = regexp.MustCompile(`^  PRIMARY KEY \((.*)\)$`)
	reMsInsert = regexp.MustCompile(`^INSERT INTO (\w+) \(([^)]*)\) VALUES$`)
)

// msTable is what the seed conversion needs to know of a table.
type msTable struct {
	keys     [][]string      // primary key and unique indexes
	nullable map[string]bool // column -> may be NULL
}

// ConvertMSSQL returns the SQL Server schema and seed for the PostgreSQL
// schema and seed that Generate made.
func ConvertMSSQL(pgSchema, pgSeed string) (schema, seed string, err error) {
	tables := map[string]*msTable{}
	var out strings.Builder
	out.WriteString(mssqlSchemaHeader)
	var t *msTable
	body := false
	for _, line := range strings.Split(pgSchema, "\n") {
		if !body {
			body = reMsCreate.MatchString(line)
			if !body {
				continue
			}
		}
		switch m := reMsCreate.FindStringSubmatch(line); {
		case m != nil:
			t = &msTable{nullable: map[string]bool{}}
			tables[strings.ToLower(m[1])] = t
			line = "CREATE TABLE " + m[1] + " ("
		case line == ");" || line == "":
		case reMsPK.MatchString(line):
			t.keys = append(t.keys, splitList(reMsPK.FindStringSubmatch(line)[1]))
		case reMsIndex.MatchString(line):
			ix := reMsIndex.FindStringSubmatch(line)
			cols := splitList(ix[4])
			it := tables[strings.ToLower(ix[3])]
			if it == nil {
				return "", "", fmt.Errorf("index %s on unknown table %s", ix[2], ix[3])
			}
			if ix[1] != "" {
				it.keys = append(it.keys, cols)
				var where []string
				for _, c := range cols {
					if it.nullable[strings.ToLower(c)] {
						where = append(where, c+" IS NOT NULL")
					}
				}
				if len(where) > 0 {
					line = strings.TrimSuffix(line, ";") + " WHERE " + strings.Join(where, " AND ") + ";"
				}
			}
		default:
			m := reMsCol.FindStringSubmatch(line)
			if m == nil || t == nil {
				return "", "", fmt.Errorf("cannot convert %q", line)
			}
			def, err := mssqlColumn(m[2])
			if err != nil {
				return "", "", fmt.Errorf("column %s: %w", m[1], err)
			}
			t.nullable[strings.ToLower(m[1])] = !strings.Contains(def, "NOT NULL")
			line = "  " + m[1] + " " + def + m[3]
		}
		out.WriteString(line + "\n")
	}
	if len(tables) < 50 {
		return "", "", fmt.Errorf("only %d tables found", len(tables))
	}
	seed, err = mssqlSeed(pgSeed, tables)
	return strings.TrimRight(out.String(), "\n") + "\n", seed, err
}

func mssqlColumn(def string) (string, error) {
	r := strings.NewReplacer(
		" GENERATED BY DEFAULT AS IDENTITY", " IDENTITY(1,1)",
		"double precision", "float",
	)
	def = r.Replace(def)
	switch typ, rest, _ := strings.Cut(def, " "); {
	case strings.HasPrefix(typ, "varchar("):
		if n, _ := strconv.Atoi(strings.TrimSuffix(strings.TrimPrefix(typ, "varchar("), ")")); n > 4000 {
			typ = "varchar(max)" // nvarchar(n) ends at 4000
		}
		def = "n" + typ + " " + rest
	case typ == "text":
		def = "nvarchar(max) " + rest
	case typ == "timestamp":
		def = "datetime2(0) " + rest
	case typ == "integer":
		def = "int " + rest // as information_schema names it (gamewe db migrate compares)
	case typ == "smallint", typ == "bigint", typ == "real", typ == "float", typ == "date":
	default:
		return "", fmt.Errorf("type %s not supported", typ)
	}
	return strings.TrimSpace(nString(def)), nil
}

// mssqlSeed turns "INSERT INTO t (cols) VALUES ... ON CONFLICT DO NOTHING;"
// into an INSERT ... SELECT that skips the rows whose key exists.
func mssqlSeed(pg string, tables map[string]*msTable) (string, error) {
	var out strings.Builder
	out.WriteString("-- gameWE - collector: default data for Microsoft SQL Server.\n" +
		"-- GENERATED by tools/schemagen from the PostgreSQL file: do not edit, run: make schema\n" +
		"-- The same rows as internal/schema/mysql/seed.sql (see there); every INSERT\n" +
		"-- skips the rows whose key exists, so it adds missing rows and changes nothing else.\n\n")
	header := true
	tail := ""
	var body []string
	var dedup func(string) bool
	for _, line := range strings.Split(pg, "\n") {
		if header && (strings.HasPrefix(line, "--") || line == "") {
			continue
		}
		header = false
		if strings.HasPrefix(line, "SET client_encoding") {
			continue
		}
		if m := reMsInsert.FindStringSubmatch(line); m != nil {
			t := tables[strings.ToLower(m[1])]
			if t == nil {
				return "", fmt.Errorf("seed: unknown table %s", m[1])
			}
			cols := splitList(m[2])
			have := map[string]bool{}
			for _, c := range cols {
				have[strings.ToLower(c)] = true
			}
			var or []string
			for _, k := range t.keys {
				var and []string
				for _, c := range k {
					if !have[strings.ToLower(c)] {
						and = nil
						break
					}
					and = append(and, "t."+c+" = v."+c)
				}
				if len(and) > 0 {
					or = append(or, "("+strings.Join(and, " AND ")+")")
				}
			}
			if len(or) == 0 {
				return "", fmt.Errorf("seed: no key of %s in (%s)", m[1], m[2])
			}
			out.WriteString("INSERT INTO " + m[1] + " (" + m[2] + ") SELECT * FROM (VALUES\n")
			tail = ") AS v (" + m[2] + ") WHERE NOT EXISTS (SELECT 1 FROM " + m[1] + " t WHERE " + strings.Join(or, " OR ") + ");"
			dedup = newDedup(cols, t.keys)
			body = nil
			continue
		}
		if tail == "" {
			out.WriteString(line + "\n")
			continue
		}
		if strings.HasPrefix(strings.TrimSpace(line), "--") {
			body = append(body, line)
			continue
		}
		s, end := strings.CutSuffix(line, " ON CONFLICT DO NOTHING;")
		// A row whose key an earlier row of the statement has is left out:
		// MariaDB's INSERT IGNORE keeps the first, SQL Server would fail.
		var kept []string
		for _, tup := range tuples(s) {
			if dedup(tup) {
				kept = append(kept, nString(tup))
			}
		}
		if len(kept) > 0 {
			body = append(body, indent(s)+strings.Join(kept, ", ")+",")
		}
		if end {
			last := len(body) - 1
			for last >= 0 && strings.HasPrefix(strings.TrimSpace(body[last]), "--") {
				last--
			}
			body[last] = strings.TrimSuffix(body[last], ",")
			out.WriteString(strings.Join(body, "\n") + "\n" + tail + "\n")
			tail = ""
		}
	}
	if tail != "" {
		return "", fmt.Errorf("seed: unterminated INSERT")
	}
	return strings.TrimRight(out.String(), "\n") + "\n", nil
}

// newDedup returns a filter that is false for a row (tuple text) whose
// values of a key were seen before.
func newDedup(cols []string, keys [][]string) func(string) bool {
	pos := map[string]int{}
	for i, c := range cols {
		pos[strings.ToLower(c)] = i
	}
	seen := map[string]bool{}
	return func(tup string) bool {
		vals := splitValues(strings.TrimSuffix(strings.TrimPrefix(tup, "("), ")"))
		fresh := true
		for ki, k := range keys {
			id := fmt.Sprint(ki)
			for _, c := range k {
				i, ok := pos[strings.ToLower(c)]
				if !ok || i >= len(vals) {
					id = ""
					break
				}
				id += "\x00" + strings.ToLower(strings.TrimSpace(vals[i])) // the collation ignores case
			}
			if id == "" {
				continue
			}
			if seen[id] {
				fresh = false
			}
			seen[id] = true
		}
		return fresh
	}
}

// tuples returns the (...) groups of a line of a VALUES list.
func tuples(line string) []string {
	var out []string
	depth, start := 0, 0
	for i := 0; i < len(line); i++ {
		switch line[i] {
		case '\'':
			i = quoteEnd(line, i)
		case '(':
			if depth == 0 {
				start = i
			}
			depth++
		case ')':
			depth--
			if depth == 0 {
				out = append(out, line[start:i+1])
			}
		}
	}
	return out
}

// splitValues splits a tuple's inside at the commas outside strings.
func splitValues(s string) []string {
	var out []string
	start := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '\'':
			i = quoteEnd(s, i)
		case ',':
			out = append(out, s[start:i])
			start = i + 1
		}
	}
	return append(out, s[start:])
}

// quoteEnd returns the index of the quote closing the literal at s[i].
func quoteEnd(s string, i int) int {
	for j := i + 1; j < len(s); j++ {
		if s[j] == '\'' {
			if j+1 < len(s) && s[j+1] == '\'' {
				j++
				continue
			}
			return j
		}
	}
	return len(s)
}

func indent(line string) string { return line[:len(line)-len(strings.TrimLeft(line, " "))] }

// nString prefixes the string literals with N (Unicode literals).
func nString(line string) string {
	var b strings.Builder
	for i := 0; i < len(line); i++ {
		c := line[i]
		if c != '\'' {
			b.WriteByte(c)
			continue
		}
		j := i + 1
		for j < len(line) {
			if line[j] == '\'' {
				if j+1 < len(line) && line[j+1] == '\'' {
					j += 2
					continue
				}
				break
			}
			j++
		}
		b.WriteString("N" + line[i:min(j+1, len(line))])
		i = j
	}
	return b.String()
}

func splitList(s string) []string {
	var out []string
	for _, p := range strings.Split(s, ",") {
		out = append(out, strings.TrimSpace(p))
	}
	return out
}

var reMsGrant = regexp.MustCompile(`^(GRANT|REVOKE) ([A-Z, ]+?)(?: \(([^)]*)\))? ON (\w+) (TO|FROM) (\w+);$`)

// ConvertMSSQLGrants turns the PostgreSQL table and column grants of the web
// users into SQL Server grants (the same syntax for these, without the
// schema and sequence rights).
func ConvertMSSQLGrants(pg, mysql string) (string, error) {
	var out strings.Builder
	out.WriteString(`-- gameWE - collector: rights of the database users for Microsoft SQL Server.
-- GENERATED by tools/schemagen from the PostgreSQL file: do not edit, run: make schema
-- The same table and column rights as internal/schema/mysql/grants.sql
-- (MariaDB). ` + "`gamewe db migrate`" + ` runs it as the collector user (db_owner of
-- the database, schema/mssql/init/); the database users gamewe_web and
-- gamewe_web_admin are created there.

-- gamewe_web loses the rights the tables below withhold from it.
`)
	// The REVOKEs of the MariaDB file (a block there) are plain statements here.
	for _, line := range strings.Split(mysql, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "REVOKE ") {
			out.WriteString(strings.NewReplacer("`", "", "'gamewe_web'@'%'", "gamewe_web").Replace(line) + "\n")
		}
	}
	out.WriteString("\n")
	n := 0
	for _, line := range strings.Split(pg, "\n") {
		m := reMsGrant.FindStringSubmatch(line)
		if m == nil || !strings.HasPrefix(m[6], "gamewe_web") {
			continue
		}
		out.WriteString(line + "\n")
		n++
	}
	if n < 50 {
		return "", fmt.Errorf("only %d grants found", n)
	}
	out.WriteString("\n-- gamewe_web_admin reads everything (including RCON passwords, to manage the servers).\nGRANT SELECT ON SCHEMA::dbo TO gamewe_web_admin;\n")
	return out.String(), nil
}
