// Command schemagen derives the PostgreSQL schema and default data from the
// MariaDB / MySQL files, so both databases always have the same tables,
// columns and rows:
//
//	internal/schema/mysql/schema.sql  -> internal/schema/postgres/schema.sql
//	internal/schema/mysql/seed.sql    -> internal/schema/postgres/seed.sql
//	internal/schema/mysql/grants.sql  -> internal/schema/postgres/grants.sql
//
// Run it from the repository root (`make schema` does).
package main

import (
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	if err := run("."); err != nil {
		fmt.Fprintln(os.Stderr, "schemagen:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	schema, err := os.ReadFile(root + "/internal/schema/mysql/schema.sql")
	if err != nil {
		return err
	}
	seed, err := os.ReadFile(root + "/internal/schema/mysql/seed.sql")
	if err != nil {
		return err
	}
	pgSchema, pgSeed, err := Generate(string(schema), string(seed))
	if err != nil {
		return err
	}
	grants, err := os.ReadFile(root + "/internal/schema/mysql/grants.sql")
	if err != nil {
		return err
	}
	pgGrants, err := ConvertGrants(string(grants))
	if err != nil {
		return err
	}
	dir := root + "/internal/schema/postgres/"
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(dir+"grants.sql", []byte(pgGrants), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(dir+"schema.sql", []byte(pgSchema), 0o644); err != nil {
		return err
	}
	return os.WriteFile(dir+"seed.sql", []byte(pgSeed), 0o644)
}

// Generate returns the PostgreSQL schema (tables and indexes) and the
// PostgreSQL seed for the MySQL schema and seed.
func Generate(mysqlSchema, mysqlSeed string) (schema, seed string, err error) {
	tables, err := ConvertTables(mysqlSchema)
	if err != nil {
		return "", "", err
	}
	seed, err = ConvertSeed(mysqlSeed)
	if err != nil {
		return "", "", err
	}
	return schemaHeader + tables, seed, nil
}

const generatedNote = "-- GENERATED by tools/schemagen from the MariaDB file: do not edit, run: make schema\n"

const schemaHeader = `-- gameWE - collector: HLstatsX database schema for PostgreSQL (13 or newer).
` + generatedNote + `--
-- The same tables, columns and defaults as internal/schema/mysql/schema.sql
-- (MariaDB / MySQL). Identifiers are unquoted, so PostgreSQL folds them to
-- lower case: hlstats_Players and hlstats_players are the same table, and
-- queries written for MariaDB work unchanged as long as they do not quote
-- names. Differences to MariaDB:
--   * unsigned integer types are the next larger signed type
--     (tinyint -> smallint, smallint unsigned -> integer, int unsigned -> bigint)
--   * ENUM('0','1') columns are varchar with a CHECK constraint
--   * AUTO_INCREMENT columns are identity columns
--   * char(n) columns are varchar(n) (no blank padding)
--   * hlstats_Livestats is an UNLOGGED table (MEMORY in MariaDB): it is empty
--     after a crash of the database server
--   * the zero dates of MariaDB ('0000-00-00') are '1970-01-01'
--   * index names are prefixed with the table name, prefix and hash
--     indexes are normal indexes
--
-- Compiled into the collector: gamewe db migrate creates a new database
-- from it (and seed.sql, grants.sql) and adds what an older one lacks.

SET client_encoding = 'UTF8';

`

var (
	reCreate = regexp.MustCompile("^CREATE TABLE `([^`]+)` \\($")
	reCol    = regexp.MustCompile("^  `([^`]+)` (\\w+)(\\(([^)]*)\\))?( unsigned)?(.*?),?$")
	reKey    = regexp.MustCompile("^  (PRIMARY KEY|UNIQUE KEY `([^`]+)`|KEY `([^`]+)`) \\((.*?)\\)( USING \\w+)?,?$")
	reEnd    = regexp.MustCompile("^\\) ENGINE=(\\w+)")
	reKeyCol = regexp.MustCompile("`([^`]+)`(\\(\\d+\\))?")
)

// ConvertTables converts the CREATE TABLE statements of a mariadb-dump.
func ConvertTables(mysql string) (string, error) {
	var out, idx strings.Builder
	var table string
	var cols []string
	n := 0
	for _, line := range strings.Split(mysql, "\n") {
		if m := reCreate.FindStringSubmatch(line); m != nil {
			table, cols = m[1], nil
			idx.Reset()
			continue
		}
		if table == "" {
			continue
		}
		if m := reEnd.FindStringSubmatch(line); m != nil {
			kind := "TABLE"
			if m[1] == "MEMORY" {
				kind = "UNLOGGED TABLE"
			}
			fmt.Fprintf(&out, "CREATE %s %s (\n  %s\n);\n%s", kind, table, strings.Join(cols, ",\n  "), idx.String())
			table = ""
			n++
			continue
		}
		if m := reKey.FindStringSubmatch(line); m != nil {
			var names []string
			for _, k := range reKeyCol.FindAllStringSubmatch(m[4], -1) {
				names = append(names, k[1]) // prefix lengths are dropped
			}
			list := strings.Join(names, ", ")
			switch {
			case m[1] == "PRIMARY KEY":
				cols = append(cols, "PRIMARY KEY ("+list+")")
			case m[2] != "":
				fmt.Fprintf(&idx, "CREATE UNIQUE INDEX %s_%s ON %s (%s);\n", table, m[2], table, list)
			default:
				fmt.Fprintf(&idx, "CREATE INDEX %s_%s ON %s (%s);\n", table, m[3], table, list)
			}
			continue
		}
		m := reCol.FindStringSubmatch(line)
		if m == nil {
			return "", fmt.Errorf("table %s: cannot parse %q", table, line)
		}
		def, err := column(m[1], strings.ToLower(m[2]), m[4], m[5] != "", strings.TrimSpace(m[6]))
		if err != nil {
			return "", fmt.Errorf("table %s: %w", table, err)
		}
		cols = append(cols, def)
	}
	if n < 50 {
		return "", fmt.Errorf("only %d tables found", n)
	}
	return out.String(), nil
}

func column(name, typ, args string, unsigned bool, rest string) (string, error) {
	var pg, check string
	switch typ {
	case "tinyint":
		pg = "smallint"
	case "smallint":
		pg = "smallint"
		if unsigned {
			pg = "integer"
		}
	case "mediumint":
		pg = "integer"
	case "int":
		pg = "integer"
		if unsigned {
			pg = "bigint"
		}
	case "bigint":
		pg = "bigint"
	case "float":
		pg = "real"
	case "double":
		pg = "double precision"
	case "varchar", "char":
		pg = "varchar(" + args + ")"
	case "text", "mediumtext", "longtext", "tinytext":
		pg = "text"
	case "date":
		pg = "date"
	case "datetime":
		pg = "timestamp"
	case "enum":
		width := 0
		for _, v := range strings.Split(args, ",") {
			width = max(width, len(strings.Trim(v, "'")))
		}
		pg = fmt.Sprintf("varchar(%d)", width)
		check = fmt.Sprintf(" CHECK (%s IN (%s))", name, args)
	default:
		return "", fmt.Errorf("column %s: type %s not supported", name, typ)
	}
	notNull := strings.Contains(rest, "NOT NULL")
	auto := strings.Contains(rest, "AUTO_INCREMENT")
	var def string
	if i := strings.Index(rest, "DEFAULT "); i >= 0 {
		def = strings.TrimSpace(rest[i+len("DEFAULT "):])
		switch def {
		case "NULL":
			def = ""
		case "'0000-00-00 00:00:00'":
			def = "'1970-01-01 00:00:00'"
		case "'0000-00-00'":
			def = "'1970-01-01'"
		}
	}
	s := name + " " + pg
	if auto {
		s += " GENERATED BY DEFAULT AS IDENTITY"
	}
	if notNull {
		s += " NOT NULL"
	}
	if def != "" {
		s += " DEFAULT " + def
	}
	return s + check, nil
}

// ConvertSeed turns the MySQL default data (INSERT IGNORE, MySQL string
// escapes) into PostgreSQL (ON CONFLICT DO NOTHING, standard strings).
func ConvertSeed(mysql string) (string, error) {
	var out strings.Builder
	out.WriteString("-- gameWE - collector: default data for PostgreSQL.\n" + generatedNote +
		"-- The same rows as internal/schema/mysql/seed.sql (see there); every INSERT\n" +
		"-- is ON CONFLICT DO NOTHING, so it adds missing rows and changes nothing else.\n\n")
	in := false
	header := true
	for _, line := range strings.Split(mysql, "\n") {
		if header && strings.HasPrefix(line, "--") {
			continue // the MySQL file's header describes the MySQL file
		}
		header = false
		switch {
		case strings.HasPrefix(line, "SET NAMES"):
			line = "SET client_encoding = 'UTF8';"
		case strings.HasPrefix(line, "INSERT IGNORE INTO "):
			line = "INSERT INTO " + strings.TrimPrefix(line, "INSERT IGNORE INTO ")
			in = true
		}
		if in && !strings.HasPrefix(strings.TrimSpace(line), "--") {
			var err error
			if line, err = pgLiterals(line); err != nil {
				return "", err
			}
			if strings.HasSuffix(line, ";") {
				line = strings.TrimSuffix(line, ";") + " ON CONFLICT DO NOTHING;"
				in = false
			}
		}
		out.WriteString(line + "\n")
	}
	return strings.TrimRight(out.String(), "\n") + "\n", nil
}

// pgLiterals rewrites MySQL string literals ('it”s', 'a\\b', 'it\'s') as
// PostgreSQL standard literals, and strips trailing -- comments.
func pgLiterals(line string) (string, error) {
	var b strings.Builder
	for i := 0; i < len(line); i++ {
		c := line[i]
		if c == '-' && i+1 < len(line) && line[i+1] == '-' {
			return strings.TrimRight(b.String(), " "), nil
		}
		if c != '\'' {
			b.WriteByte(c)
			continue
		}
		b.WriteByte('\'')
		i++
		for ; ; i++ {
			if i >= len(line) {
				return "", fmt.Errorf("unterminated string in %q", line)
			}
			switch line[i] {
			case '\\':
				i++
				switch line[i] {
				case 'n':
					b.WriteByte('\n')
				case '\'':
					b.WriteString("''")
				default:
					b.WriteByte(line[i])
				}
				continue
			case '\'':
				if i+1 < len(line) && line[i+1] == '\'' {
					b.WriteString("''")
					i++
					continue
				}
				b.WriteByte('\'')
			default:
				b.WriteByte(line[i])
				continue
			}
			break
		}
	}
	return b.String(), nil
}

var reGrant = regexp.MustCompile("^GRANT ([A-Z, ]+?)(?: \\(([^)]*)\\))? ON `([^`]+)` TO '([^']+)'@'%';$")

// ConvertGrants turns the MariaDB table and column grants of the web users
// into PostgreSQL grants and adds what PostgreSQL needs besides: CONNECT,
// schema USAGE, the collector's rights and the identity sequences.
func ConvertGrants(mysql string) (string, error) {
	var out strings.Builder
	out.WriteString(`-- gameWE - collector: rights of the database users for PostgreSQL.
` + generatedNote + `-- The same table and column rights as internal/schema/mysql/grants.sql
-- (MariaDB), plus the sequences of the identity columns. ` + "`gamewe db migrate`" + `
-- runs it as the collector role, which owns the tables it created; CONNECT
-- and the schema rights are granted once by schema/postgres/init/.

-- gamewe (the collector): rows of every table (also those an admin created).
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO gamewe;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO gamewe;

-- gamewe_web_admin reads everything (including RCON passwords, to manage the
-- servers) and may use the sequences for its inserts.
GRANT SELECT ON ALL TABLES IN SCHEMA public TO gamewe_web_admin;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO gamewe_web_admin;

`)
	n := 0
	for _, line := range strings.Split(mysql, "\n") {
		if strings.HasPrefix(line, "-- gamewe_web (public web pages)") {
			out.WriteString("-- gamewe_web (public web pages): SELECT on every table, except hlstats_Users\n-- and hlstats_Events_Chat, and without hlstats_Servers.rcon_password,\n-- log_secret and log_secret_changed and hlstats_Events_Connects.ipAddress.\n")
		}
		if strings.HasPrefix(line, "-- gamewe_web_admin (web admin pages)") {
			out.WriteString("\n-- gamewe_web_admin: edits the settings and reference tables, and on\n-- players only skill, hideranking and clan.\n")
		}
		if !strings.HasPrefix(line, "GRANT ") {
			continue
		}
		m := reGrant.FindStringSubmatch(line)
		if m == nil {
			return "", fmt.Errorf("cannot convert %q", line)
		}
		cols := ""
		if m[2] != "" {
			cols = " (" + strings.ReplaceAll(m[2], "`", "") + ")"
		}
		fmt.Fprintf(&out, "GRANT %s%s ON %s TO %s;\n", m[1], cols, m[3], m[4])
		n++
	}
	if n < 50 {
		return "", fmt.Errorf("only %d grants found", n)
	}
	out.WriteString(`
-- A role gamewe_admin (the manual setup in the web frontend's README) may
-- queue ranking resets too; skipped when there is none.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gamewe_admin') THEN
    GRANT SELECT, INSERT ON hlstats_gamewe_jobs TO gamewe_admin;
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO gamewe_admin', pg_get_serial_sequence('hlstats_gamewe_jobs', 'id'));
  END IF;
END
$$;
`)
	return out.String(), nil
}
